/// Runtime-owned command metadata
pub type OwnedCommandDef = CommandDef<Owned>;

/// Metadata for a positional argument slot.
#[derive(Debug, Clone, PartialEq, Eq)]
#[expect(
    clippy::exhaustive_structs,
    reason = "static config generated by derive"
)]
pub struct PositionalDef<S: Storage = Static> {
    /// Field name (used in error messages).
    pub name: S::Text,
    /// Whether the user must provide this argument.
    pub required: bool,
    /// Human-readable description (from doc comment).
    pub desc: S::Text,
    /// Label shown in help; the field name when empty.
    pub label: S::Text,
    /// Value used when the argument is omitted; none when empty.
    pub default_value: S::Text,
    /// When true, omit from generated help.
    pub hidden: bool,
    /// Whether help shows the label as accepting more than one value.
    pub spread: bool,
}

impl<S: Storage> CommandDef<S> {
    /// Command name
    pub fn name(&self) -> &str {
        self.name.as_ref()
    }

    /// Declared flags
    pub fn flags(&self) -> &[FlagDef<S>] {
        self.flags.as_ref()
    }

    /// Generic metadata tags
    pub fn tags(&self) -> &[(S::Text, S::Text)] {
        self.tags.as_ref()
    }

    /// Scan one invocation against this command shape
    pub fn scan<'a>(&'a self, args: &'a [&'a str]) -> Result<crate::parse::Scan<'a>, Error> {
        let policy = crate::parse::Policy::from_definition(self);
        crate::parse::scan_with_policy(
            args,
            self.flags(),
            policy,
            self.on_unknown,
            self.style,
            self.permute,
        )
    }
}
