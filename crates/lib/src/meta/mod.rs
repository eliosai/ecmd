//! Command metadata and the `Command` trait

use crate::error::Error;
use crate::parse::{FlagDef, OnUnknown};
use crate::policy::{ExclusiveRule, NumericOperandRule, ValueRule};
use crate::style::{HelpStyle, Style};

mod owned;

/// Storage used by command metadata
pub trait Storage: 'static {
    /// Text storage
    type Text: AsRef<str> + 'static;
    /// Sequence storage
    type List<T: 'static>: AsRef<[T]>;
}

/// Borrowed static command metadata
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum Static {}

impl Storage for Static {
    type Text = &'static str;
    type List<T: 'static> = &'static [T];
}

/// Owned command metadata
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum Owned {}

impl Storage for Owned {
    type Text = String;
    type List<T: 'static> = Vec<T>;
}

/// The trait implemented by `#[derive(Command)]` structs.
pub trait Command: Sized {
    /// Static metadata describing this command.
    fn def() -> &'static CommandDef;

    /// Parse one argument slice into the command
    fn parse(args: &[&str]) -> Result<Self, Error>;
}

/// Static metadata for a command, generated by the derive macro.
#[derive(Debug, Clone, PartialEq, Eq)]
#[expect(
    clippy::exhaustive_structs,
    clippy::struct_excessive_bools,
    reason = "static config generated by derive"
)]
pub struct CommandDef<S: Storage = Static> {
    /// Command name (e.g., "cd").
    pub name: S::Text,
    /// Short description (first line of doc comment).
    pub about: S::Text,
    /// Override for the auto-generated usage in help display.
    pub short_doc: S::Text,
    /// Parsing style.
    pub style: Style,
    /// Help dialect rendered by [`CommandDef::help`].
    pub help_style: HelpStyle,
    /// How unrecognized flags are handled.
    pub on_unknown: OnUnknown,
    /// Whether options may follow positional operands.
    pub permute: bool,
    /// Declared flags.
    pub flags: S::List<FlagDef<S>>,
    /// Declared positional arguments (in order).
    pub positionals: S::List<PositionalDef<S>>,
    /// Whether a rest-args (`Operands`) field exists.
    pub has_rest: bool,
    /// Label for the rest slot in help; `args` when empty.
    pub rest_label: S::Text,
    /// Whether the rest slot is omitted from generated help.
    pub rest_hidden: bool,
    /// Description shown for the rest slot.
    pub rest_desc: S::Text,
    /// Value the rest slot reports when it is empty; none when empty.
    pub rest_default: S::Text,
    /// Whether the rest slot shows as required.
    pub rest_required: bool,
    /// Missing-value behavior keyed by flag identity.
    pub value_rules: S::List<ValueRule<S>>,
    /// Legacy numeric operand routes.
    pub numeric_operands: S::List<NumericOperandRule>,
    /// First-argument obsolete numeric flag target.
    pub first_numeric_value: Option<char>,
    /// Whether GNU long options require exact names.
    pub exact_long: bool,
    /// Whether the command withholds the implicit `-V` short for version.
    pub no_implicit_version: bool,
    /// Valued long options that require an attached value.
    pub equals_only: S::List<char>,
    /// Short options that require an attached value.
    pub attached_values: S::List<char>,
    /// Short options that require a separate value.
    pub separated_values: S::List<char>,
    /// Short options accepting a leading numeric value.
    pub prefixed_values: S::List<char>,
    /// Option memberships in mutually exclusive groups.
    pub exclusive_groups: S::List<ExclusiveRule>,
    /// Generic key-value tags for downstream consumers.
    pub tags: S::List<(S::Text, S::Text)>,
    /// Body paragraphs between summary and Options.
    pub description: S::List<S::Text>,
    /// Content placed after auto-generated Options section.
    pub extra: S::List<S::Text>,
    /// Exit Status section content.
    pub exit_status: S::List<S::Text>,
}

